const MARK_COLORS = { black: '#000000' };
const markColors = (tokens) => ({ ...MARK_COLORS, ink: tokens.color.ink, paper: tokens.color.canvas, orange: tokens.color.accent });

const recolor = (svg, hex) => svg.replaceAll('fill="#000000"', `fill="${hex}"`);
const symbolArms = (svg) => svg.match(/<g fill="#000000" transform="translate\(0 1254\) scale\(\.1 -\.1\)">[\s\S]*?<\/g>/)[0];

// Proposed simplified Spindle for 16 px: eight identical bent arms on an exact
// 45° rotation, thicker relative to size and with a larger central void.
export const SMALL_SPINDLE = { width: 80, inner: [-140, -180], bend: [-140, -320], outer: [0, -430] };

function smallSpindlePath({ width, inner, bend, outer }) {
  const normal = (a, b) => { const dx = b[0] - a[0], dy = b[1] - a[1], l = Math.hypot(dx, dy); return [-dy / l, dx / l]; };
  const n1 = normal(inner, bend), n2 = normal(bend, outer);
  const offset = (p, n, side) => [p[0] + n[0] * side * width / 2, p[1] + n[1] * side * width / 2];
  const miter = (side) => {
    const p1 = offset(inner, n1, side), d1 = [bend[0] - inner[0], bend[1] - inner[1]];
    const p2 = offset(bend, n2, side), d2 = [outer[0] - bend[0], outer[1] - bend[1]];
    const t = ((p2[0] - p1[0]) * d2[1] - (p2[1] - p1[1]) * d2[0]) / (d1[0] * d2[1] - d1[1] * d2[0]);
    return [p1[0] + d1[0] * t, p1[1] + d1[1] * t];
  };
  const outline = [offset(inner, n1, 1), miter(1), offset(outer, n2, 1), offset(outer, n2, -1), miter(-1), offset(inner, n1, -1)];
  const arms = [];
  for (let k = 0; k < 8; k += 1) {
    const c = Math.cos(k * Math.PI / 4), s = Math.sin(k * Math.PI / 4);
    const points = outline.map(([x, y]) => [x * c - y * s, x * s + y * c].map(v => (Math.round(v * 10) / 10 || 0)));
    arms.push(`M${points.map(p => p.join(' ')).join('L')}Z`);
  }
  return arms;
}

function smallSymbolSvg(hex) {
  const arms = smallSpindlePath(SMALL_SPINDLE).map((d, i) => `    <path id="arm-${i + 1}" d="${d}"/>`);
  return `<svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" viewBox="-480 -480 960 960" fill="none">
  <title>Perpeto Spindle, simplified for 16 px (proposal, not approved)</title>
  <g fill="${hex}">
${arms.join('\n')}
  </g>
</svg>
`;
}

// Tile icons reuse the established badge geometry from brand/motion/variants/badge.svg.
function tileSvg(arms, { tile, mark, size = 1024, inset = 0, radius = 0 }) {
  const span = 816 / (1 - 2 * inset);
  const min = 627 - span / 2, minY = 594 - span / 2;
  const r = radius ? ` rx="${(radius * span / size).toFixed(1)}"` : '';
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${min} ${minY} ${span} ${span}" width="${size}" height="${size}">`
    + `<title>Perpeto app icon</title><rect x="219" y="186" width="816" height="816"${r} fill="${tile}"/>`
    + `<g transform="translate(627 594) scale(.68) translate(-627 -594)">${arms.replace('fill="#000000"', `fill="${mark}"`)}</g></svg>\n`;
}

function faviconSvg(arms, tokens) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="219 186 816 816" width="32" height="32">`
    + `<style>.mark{fill:${tokens.color.ink}}@media (prefers-color-scheme: dark){.mark{fill:${tokens.color.canvas}}}</style>`
    + `<title>Perpeto</title><g class="mark">${arms.replace(' fill="#000000"', '')}</g></svg>\n`;
}

function composeRow(images, gap, background) {
  const width = images.reduce((sum, img) => sum + img.width, 0) + gap * (images.length + 1);
  const height = Math.max(...images.map(img => img.height)) + gap * 2;
  const data = new Uint8Array(width * height * 4);
  const [r, g, b] = hexToRgb(background);
  for (let p = 0; p < width * height; p += 1) data.set([r, g, b, 255], p * 4);
  let x0 = gap;
  for (const img of images) {
    for (let y = 0; y < img.height; y += 1) {
      for (let x = 0; x < img.width; x += 1) {
        const s = (y * img.width + x) * 4, o = ((y + gap) * width + x0 + x) * 4, a = img.data[s + 3] / 255;
        for (let c = 0; c < 3; c += 1) data[o + c] = Math.round(img.data[s + c] * a + data[o + c] * (1 - a));
      }
    }
    x0 += img.width + gap;
  }
  return { width, height, data };
}

function stack(rows, background) {
  const width = Math.max(...rows.map(r => r.width));
  const height = rows.reduce((sum, r) => sum + r.height, 0);
  const data = new Uint8Array(width * height * 4);
  const [r, g, b] = hexToRgb(background);
  for (let p = 0; p < width * height; p += 1) data.set([r, g, b, 255], p * 4);
  let y0 = 0;
  for (const row of rows) {
    for (let y = 0; y < row.height; y += 1) data.set(row.data.subarray(y * row.width * 4, (y + 1) * row.width * 4), ((y0 + y) * width) * 4);
    y0 += row.height;
  }
  return { width, height, data };
}

// Legibility sheet: master (top two rows) and proposed small variant (bottom two),
// each at 16, 24 and 32 px, ink on paper then paper on ink, enlarged 8× nearest-neighbour.
function legibilitySheet(master, small, tokens) {
  const { ink, canvas } = tokens.color;
  const row = (svg, fg, bg) => composeRow([16, 24, 32].flatMap(size => {
    const img = renderSvg(svg, size, size, { background: bg, recolor: () => fg });
    return [enlarge(img, 8), enlarge(img, 1)];
  }), 16, bg);
  return stack([row(master, ink, canvas), row(master, canvas, ink), row(small, ink, canvas), row(small, canvas, ink)], canvas);
}

export function generateAssets(tokens) {
  const files = [];
  const colors = markColors(tokens);
  const sources = {
    symbol: read('brand/identity/perpeto-symbol.svg'),
    wordmark: read('brand/identity/perpeto-wordmark.svg'),
    lockup: read('brand/identity/perpeto-lockup.svg'),
  };
  for (const [kind, svg] of Object.entries(sources)) {
    files.push([`assets/perpeto-${kind}.svg`, svg]);
    for (const [name, hex] of Object.entries(colors)) files.push([`assets/perpeto-${kind}-${name}.svg`, recolor(svg, hex)]);
  }
  const arms = symbolArms(sources.symbol);
  const small = smallSymbolSvg('#000000');
  for (const [name, hex] of Object.entries(colors)) files.push([`assets/proposed/perpeto-symbol-small-${name}.svg`, smallSymbolSvg(hex)]);

  const png = (svg, size, options) => encodePng(renderSvg(svg, size, size, options));
  const { ink, canvas } = tokens.color;

  // App icons: ink tile, paper Spindle. Full bleed for iOS and web (the system masks it);
  // macOS uses Apple's 824/1024 rounded tile on a transparent canvas.
  const iosIcon = tileSvg(arms, { tile: ink, mark: canvas });
  const macIcon = tileSvg(arms, { tile: ink, mark: canvas, inset: 100 / 1024, radius: 185.4 });
  files.push(['assets/app-icon/perpeto-app-icon.svg', iosIcon]);
  files.push(['assets/app-icon/perpeto-app-icon-macos.svg', macIcon]);
  for (const size of [1024, 512, 256, 180, 128, 64]) files.push([`assets/app-icon/perpeto-app-icon-${size}.png`, png(iosIcon, size)]);
  for (const size of [1024, 512, 256, 128, 64, 32, 16]) files.push([`assets/app-icon/macos/perpeto-app-icon-macos-${size}.png`, png(macIcon, size)]);

  // Favicons: transparent ink Spindle (master geometry), plus a dark-scheme SVG.
  const inkSymbol = recolor(sources.symbol, ink);
  const favicon = Object.fromEntries([16, 32, 48].map(size => [size, png(inkSymbol, size)]));
  files.push(['assets/favicon/favicon.svg', faviconSvg(arms, tokens)]);
  for (const [size, buffer] of Object.entries(favicon)) files.push([`assets/favicon/favicon-${size}.png`, buffer]);
  files.push(['assets/favicon/favicon.ico', encodeIco([favicon[16], favicon[32], favicon[48]])]);
  files.push(['assets/favicon/apple-touch-icon.png', png(iosIcon, 180)]);
  files.push(['assets/favicon/icon-192.png', png(iosIcon, 192)]);
  files.push(['assets/favicon/icon-512.png', png(iosIcon, 512)]);
  files.push(['assets/favicon/site.webmanifest', `${JSON.stringify({
    name: 'Perpeto',
    short_name: 'Perpeto',
    icons: [
      { src: 'icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any maskable' },
      { src: 'icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any maskable' },
    ],
    theme_color: canvas,
    background_color: canvas,
    display: 'standalone',
  }, null, 2)}\n`]);

  // Proposal: 16 px favicon from the simplified Spindle, for Justus to approve or reject.
  const smallFavicon = png(smallSymbolSvg(ink), 16);
  files.push(['assets/proposed/favicon-16-small.png', smallFavicon]);
  files.push(['assets/proposed/favicon-small.ico', encodeIco([smallFavicon, favicon[32], favicon[48]])]);

  // Inspection renders backing the legibility notes in assets/README.md.
  for (const size of [16, 24, 32]) {
    files.push([`assets/inspection/symbol-${size}.png`, png(inkSymbol, size, { background: canvas })]);
    files.push([`assets/inspection/symbol-small-${size}.png`, png(smallSymbolSvg(ink), size, { background: canvas })]);
  }
  files.push(['assets/inspection/legibility-sheet.png', encodePng(legibilitySheet(sources.symbol, small, tokens))]);
  return files;
}

// ---------- specimen ----------
function specimen(tokens, css) {
  const template = readFileSync(resolve(packageRoot, 'src/specimen.template.html'), 'utf8');
  const strip = (svg) => svg.replace(/<title>[^<]*<\/title>/, '').replace(/^<svg /, '<svg aria-hidden="true" ');
  const replacements = {
    '/* @tokens.css */': css,
    '<!-- @lockup -->': strip(recolor(read('brand/identity/perpeto-lockup.svg'), 'currentColor')),
    '<!-- @symbol -->': strip(recolor(read('brand/identity/perpeto-symbol.svg'), 'currentColor')),
    '<!-- @symbol-small -->': strip(smallSymbolSvg('currentColor')),
    '<!-- @app-icon -->': strip(tileSvg(symbolArms(read('brand/identity/perpeto-symbol.svg')), { tile: tokens.color.ink, mark: tokens.color.canvas, inset: 100 / 1024, radius: 185.4 })),
    '<!-- @contrast -->': [...tokens.contrast.text.map(c => ({ ...c, kind: 'Text', min: 4.5 })), ...tokens.contrast.nonText.map(c => ({ ...c, kind: 'Non-text', min: 3 }))]
      .map(({ fg, bg, ratio, kind, min }) => `<tr><td><span class="pair" style="color:var(--${fg});background:var(--${bg})">Aa</span></td><td><code>--${fg}</code> on <code>--${bg}</code></td><td>${kind}</td><td class="num">${ratio.toFixed(2)}</td><td>${ratio >= min ? 'Passes' : 'Below'} ${min}:1</td></tr>`).join('\n'),
  };
  let html = template;
  for (const [marker, value] of Object.entries(replacements)) {
    if (!html.includes(marker)) throw new Error(`specimen template is missing ${marker}`);
    html = html.replaceAll(marker, value);
  }
  return html;
}

export function generate() {
  const resolved = resolveTokens();
  const css = tokensCss(resolved);
  return [
    ['dist/tokens.css', css],
    ['dist/tokens.json', tokensJson(resolved)],
    ['dist/tokens.ts', tokensTs(resolved)],
    ['swift/PerpetoTokens.swift', tokensSwift(resolved)],
    ...generateAssets(resolved.tokens),
    ['specimen.html', specimen(resolved.tokens, css)],
  ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const files = generate();
  // Remove stale generated files; hand-written READMEs stay.
  const keep = new Set(files.map(([path]) => resolve(packageRoot, path)));
  for (const dir of ['dist', 'swift', 'assets']) {
    for (const entry of readdirSync(resolve(packageRoot, dir), { recursive: true, withFileTypes: true })) {
      const path = resolve(entry.parentPath, entry.name);
      if (entry.isFile() && entry.name !== 'README.md' && !keep.has(path)) rmSync(path);
    }
  }
  for (const [path, content] of files) {
    const target = resolve(packageRoot, path);
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, content);
  }
  console.log(`@perpeto/design-tokens: wrote ${files.length} files.`);
}
