import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, readFile, readlink, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { resolve, dirname } from 'node:path';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { repoRoot } from '../src/config.js';

const exec = promisify(execFile);
test('installer clones/updates a local fixture, repeats safely and preserves dirty/foreign paths', { timeout: 30000 }, async t => {
  const dir = await mkdtemp(resolve(tmpdir(), 'pinstall-'));
  t.after(() => rm(dir, { recursive: true, force: true }));
  const upstream = resolve(dir, 'upstream'); const install = resolve(dir, 'installed'); const bin = resolve(dir, 'bin'); const stubs = resolve(dir, 'stubs');
  await mkdir(resolve(upstream, 'packages/perpeto-cli/bin'), { recursive: true }); await mkdir(stubs);
  await writeFile(resolve(upstream, 'packages/perpeto-cli/bin/perpeto.js'), '#!/usr/bin/env node\n', { mode: 0o755 });
  const git = (...args) => exec('git', ['-C', upstream, ...args]);
  await git('init', '-b', 'main'); await git('config', 'user.email', 'fixture@example.test'); await git('config', 'user.name', 'Fixture');
  await git('add', '.'); await git('-c', 'commit.gpgsign=false', '-c', 'core.hooksPath=/dev/null', 'commit', '-m', 'fixture');
  await writeFile(resolve(stubs, 'pnpm'), '#!/bin/sh\nprintf "11.10.0\\n"\n', { mode: 0o755 });
  await writeFile(resolve(stubs, 'npm'), '#!/bin/sh\nprintf "%s\\n" "$*" >> "$INSTALL_TEST_LOG"\n', { mode: 0o755 });
  const env = { ...process.env, PATH: `${stubs}:${dirname(process.execPath)}:${process.env.PATH}`, INSTALL_TEST_LOG: resolve(dir, 'calls') };
  const args = [resolve(repoRoot, 'install/install.sh'), '--repo', upstream, '--dir', install, '--bin-dir', bin];
  const run = () => exec('/bin/sh', args, { env, timeout: 10000 });
  await run();
  assert.equal(await readlink(resolve(bin, 'perpeto')), resolve(install, 'packages/perpeto-cli/bin/perpeto.js'));
  await run();
  assert.equal(await readFile(resolve(dir, 'calls'), 'utf8'), 'run setup\nrun build\nrun setup\nrun build\n');
  await writeFile(resolve(upstream, 'update'), 'upstream'); await git('add', 'update');
  await git('-c', 'commit.gpgsign=false', '-c', 'core.hooksPath=/dev/null', 'commit', '-m', 'update');
  await run(); assert.equal(await readFile(resolve(install, 'update'), 'utf8'), 'upstream');
  await writeFile(resolve(install, 'user-work'), 'preserve');
  await assert.rejects(run(), /local changes/); assert.equal(await readFile(resolve(install, 'user-work'), 'utf8'), 'preserve');
  await rm(resolve(install, 'user-work'));
  await rm(resolve(bin, 'perpeto')); await writeFile(resolve(bin, 'perpeto'), 'another CLI');
  await assert.rejects(run(), /unrelated perpeto bin/); assert.equal(await readFile(resolve(bin, 'perpeto'), 'utf8'), 'another CLI');
});
